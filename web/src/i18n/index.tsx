interface I18nValue {
  lang: Lang;
  calendar: Calendar;
  dir: 'rtl' | 'ltr';
  t: (key: MessageKey, vars?: Record<string, string | number>) => string;
  fmt: Fmt;
  setLang: (lang: Lang) => void;
  setCalendar: (calendar: Calendar) => void;
  /** Localized error text for an API error code, falling back to a generic line. */
  errorText: (code: string) => string;
  /**
   * Heading for that error. Distinct from `errorText` because a refusal is not
   * a fault: `invalid_credentials` is headed "Sign-in failed", while a genuine
   * server error keeps the generic heading.
   */
  errorTitle: (code: string) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({
  initialLang = 'ar',
  initialCalendar = 'islamic-umalqura',
  children,
}: {
  initialLang?: Lang;
  initialCalendar?: Calendar;
  children: ReactNode;
}) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  const [calendar, setCalendarState] = useState<Calendar>(initialCalendar);

  // `<html dir>` is the single switch for the whole document. Because the
  // stylesheet uses logical properties, nothing else has to react to it.
  useEffect(() => {
    const root = document.documentElement;
    root.lang = lang;
    root.dir = lang === 'ar' ? 'rtl' : 'ltr';
  }, [lang]);

  const setLang = useCallback((next: Lang) => setLangState(next), []);
  const setCalendar = useCallback((next: Calendar) => setCalendarState(next), []);

  const fmt = useMemo(() => createFormatter(lang, calendar), [lang, calendar]);

  const t = useCallback(
    (key: MessageKey, vars?: Record<string, string | number>) => {
      const table = lang === 'ar' ? AR : EN;
      let text: string = table[key] ?? AR[key] ?? String(key);
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
        }
      }
      return text;
    },
    [lang],
  );

  const errorText = useCallback(
    (code: string) => {
      const key = `err.${code}` as MessageKey;
      const table = lang === 'ar' ? AR : EN;
      return table[key] ?? AR[key] ?? EN['err.unknown'] ?? code;
    },
    [lang],
  );

  const errorTitle = useCallback(
    (code: string) => {
      const key = ERROR_TITLES[code] ?? 'common.errorTitle';
      const table = lang === 'ar' ? AR : EN;
      return table[key] ?? EN[key] ?? EN['common.errorTitle'];
    },
    [lang],
  );

  const value = useMemo<I18nValue>(
    () => ({ lang, calendar, dir: fmt.dir, t, fmt, setLang, setCalendar, errorText, errorTitle }),
    [lang, calendar, fmt, t, setLang, setCalendar, errorText, errorTitle],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside <I18nProvider>');
  return ctx;
}
