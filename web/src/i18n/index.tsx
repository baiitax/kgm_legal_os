/**
 * True when the dictionary actually translates `key`. Screens use this to decide
 * between a localized label and a readable fallback, so a new server-side
 * status degrades to prose instead of a bare key.
 */
export function hasMessage(key: string): key is MessageKey {
  return Object.prototype.hasOwnProperty.call(AR, key);
}

/**
 * Translate a key that is only known at runtime — a status code, a category, a
 * country code coming off the wire. `t()` is typed against the dictionary, which
 * is exactly what makes static keys safe; dynamic ones go through here instead of
 * being cast, so a value the server invents tomorrow renders as readable text
 * rather than crashing the build or leaking a raw key.
 */
export function translate(
  lang: Lang,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const table: Record<string, string> = lang === 'ar' ? AR : EN;
  let text: string = table[key] ?? (AR as Record<string, string>)[key] ?? key.replace(/_/g, ' ');
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return text;
}

